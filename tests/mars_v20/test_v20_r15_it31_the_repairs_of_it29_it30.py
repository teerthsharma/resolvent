def _digest(rel: str) -> str:
    return hashlib.sha256((ROOT / rel).read_bytes()).hexdigest()[:16]


# ---------------------------------------------------------------- MARS-31-A
# The INSPECTOR withdrew "only tier 1 (committed) can be refuted" and replaced
# it with "tier 1 = a file at a stated path with a published digest and a
# regenerating command, committed or not."  V20_R15_IT29_INSPECTOR.md:414-419.
#
# MERCURY's withdrawals node satisfies the replacement rule in FULL: stated path,
# digest b2a9cc0fb1c46973 published at V20_R15_IT29_MERCURY.md:15 and :274, and a
# pytest command. The replacement rule therefore certifies it as refutable.
# It is not. Same bytes, two different answers.

WITHDRAWALS = "tests/mercury/test_v20_r15_it29_withdrawals.py"
PUBLISHED_DIGEST = "b2a9cc0fb1c46973"


def test_mars31a_a_published_digest_does_not_pin_the_result_it_certifies():
    """RED. The replacement tier rule buys byte-identity, not reproducibility.

    MERCURY published `4 RED / 4 GREEN` for this node. The INSPECTOR re-read it
    twenty-five minutes later at `5 failed, 3 passed`, digest UNCHANGED
    (V20_R15_JOURNAL.md, it.30 entry). If a published digest made a number
    refutable, an unchanged digest would reproduce the published composition.
    """
    assert _digest(WITHDRAWALS) == PUBLISHED_DIGEST, "instrument was edited; strike is void"
    r = subprocess.run(
        [sys.executable, "-m", "pytest", WITHDRAWALS, "-q", "--no-header",
         "-p", "no:cacheprovider"],
        cwd=str(ROOT), capture_output=True, text=True,
    )
    tail = r.stdout.strip().splitlines()[-1]
    assert "4 failed, 4 passed" in tail, (
        "the replacement tier rule certifies this file at its published digest; "
        "MERCURY published 4 RED / 4 GREEN against digest " + PUBLISHED_DIGEST +
        "; the same bytes now read: " + repr(tail)
    )


# ---------------------------------------------------------------- MARS-31-B
# RULING M-30 (V20_R15_IT30_MERCURY.md:88-105) disqualifies `309.047` as
# "a different object" -- _sweep(2.0) on it.13's RE-MEASURED means -- and names
# `309.015` (the formula's own literal constants) as the formula. It then
# prescribes, as the honest quote, "the band `206 - 537 GPU-s`, point `309.0`".

LIT = (16.16, 1.78, 1.68)          # V20_R15_IT8_JUPITER.md:216, as written


def _lit_sweep(e):
    return 3 * sum((s / 64.0) ** e for s in (32, 64, 128)) * sum(LIT)


def test_mars31b_the_honest_point_is_the_number_the_same_ruling_withdraws():
    """RED. M-30a withdraws `309.047` as mis-attributed; M-30 then prescribes
    `point 309.0` -- which is `309.047`, rounded. The two edits M-30 calls
    "not the same edit" contradict each other: applying `:354` reinstates at one
    decimal the number `:184` is being corrected for carrying at three."""
    import phase_c_price as pcp
    quoted_point = 309.0
    withdrawn = pcp._sweep(2.0)                  # 309.047, the "different object"
    the_formula = _lit_sweep(2.0)                # 309.015, what M-30a says is true
    assert round(the_formula, 1) == quoted_point and round(withdrawn, 1) != quoted_point, (
        "M-30's prescribed point must come from the formula it vindicates, not from "
        "the object it withdraws: formula=%.3f, withdrawn=%.3f, both round to %s"
        % (the_formula, withdrawn, quoted_point)
    )


def test_mars31b2_the_published_band_cannot_separate_the_two_objects():
    """RED. The whole of M-30 is that `309.015` and `309.047` are two objects.
    The band it prescribes as the repair, `206 - 537`, is generated by BOTH
    families and is identical at the published precision. The prescribed quote
    erases exactly the distinction the ruling was made to draw."""
    import phase_c_price as pcp
    remeasured = (pcp._sweep(1.0), pcp._sweep(3.0))
    literal = (_lit_sweep(1.0), _lit_sweep(3.0))

    def fmt(b):
        return "%d-%d" % (round(b[0]), round(b[1]))

    assert fmt(remeasured) != fmt(literal), (
        "a band both objects produce is not a repair for confusing them: "
        "re-measured -> %s (%.3f, %.3f); literal -> %s (%.3f, %.3f)"
        % (fmt(remeasured), remeasured[0], remeasured[1],
           fmt(literal), literal[0], literal[1])
    )


def test_mars31b3_the_point_is_inside_the_band_by_construction_not_by_agreement():
    """RED. `309.0` is not corroborated by the band; it is the band's own
    generator at the midpoint exponent. Two endpoints and a point drawn from one
    monotone family are ONE measurement, not three. A price quoted as
    `band + point` claims an independent centre it does not have."""
    import phase_c_price as pcp
    lo, mid, hi = pcp.s_exponent_band()
    assert not (mid == pcp._sweep(2.0) and lo == pcp._sweep(1.0) and hi == pcp._sweep(3.0)), (
        "band and point are one function at three exponents -- containment is "
        "guaranteed by monotonicity in e, not measured: %.3f / %.3f / %.3f"
        % (lo, mid, hi)
    )


