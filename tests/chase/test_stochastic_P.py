"""THEORY.md §1 constraint 2 ("Make P a transition kernel: row-stochastic, non-negative")
and §8 risk 5 ("Stochastic P may destroy expressiveness").

THEORY.md calls the row-stochastic constraint free: "two constraints on an existing,
working, tested solve -- not a new architecture", and argues the contraction
certificate becomes structural rather than measured. The certificate claim is true.
These tests ask what it costs.

Three separate things are attacked:

  A. The output range. Row-stochastic P forces (I - gamma P)^-1 to be non-negative
     with every row summing to 1/(1-gamma). z = M b is therefore a CONVEX COMBINATION
     of b's entries, scaled by 1/(1-gamma). No choice of P and no choice of gamma can
     produce a z outside [min(b), max(b)]/(1-gamma). This is not a tightness question;
     it is a closed hypothesis class.

  B. Enforcement cost per step. If the constraint is imposed by Euclidean projection
     onto the simplex (the option that keeps sigmoid's existing ridge fit), what does
     the projection do to the gradient, and are the zeros it creates recoverable?

  C. What the solve costs at 1B scale, since gamma explicit + P stochastic still
     leaves a dense d x d solve in the forward pass.
"""

