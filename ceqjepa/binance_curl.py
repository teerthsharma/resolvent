# Statistics. Two OLS columns and a Welch interval; nothing that needs a library.

def _ols(y, X):
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    resid = y - X @ beta
    dof = max(len(y) - X.shape[1], 1)
    s2 = float(resid @ resid) / dof
    cov = s2 * np.linalg.pinv(X.T @ X)
    se = np.sqrt(np.clip(np.diag(cov), 0, None))
    r2 = 1.0 - float(resid @ resid) / max(float(((y - y.mean()) ** 2).sum()), 1e-300)
    return beta, np.divide(beta, se, out=np.zeros_like(beta), where=se > 0), r2


def _z(v):
    s = v.std(ddof=1)
    return (v - v.mean()) / s if s > 0 else np.zeros_like(v)


def gate(abs_curl, spread, invvol, t_bar=3.0):
    """THE GATE. Does pre-intervention |c_T| track spread, or 1/volume?

    All three inputs are per-triangle means over the pre-intervention window, so
    the observation is the triangle and no clustering correction is owed.

    VOID when the standardized 1/volume coefficient beats the spread coefficient
    in magnitude and clears |t| > t_bar. The rule is fixed before the numbers are
    seen; this project has already shipped a bar applied in two incompatible units
    and the fix is to state the rule in one unit, in advance.
    """
    n = len(abs_curl)
    if n < 30:
        return dict(verdict="REFUSED", reason="only %d triangles" % n, n=n)
    y, x1, x2 = _z(abs_curl), _z(spread), _z(invvol)
    X = np.column_stack([np.ones(n), x1, x2])
    beta, t, r2 = _ols(y, X)
    b_sp, b_iv, t_sp, t_iv = beta[1], beta[2], t[1], t[2]
    _, _, r2_sp = _ols(y, np.column_stack([np.ones(n), x1]))
    _, _, r2_iv = _ols(y, np.column_stack([np.ones(n), x2]))
    void = abs(b_iv) > abs(b_sp) and abs(t_iv) > t_bar
    return dict(verdict="VOID" if void else "PASS", n=n,
                beta_spread=float(b_sp), t_spread=float(t_sp),
                beta_invvol=float(b_iv), t_invvol=float(t_iv),
                r2_joint=float(r2), r2_spread_only=float(r2_sp),
                r2_invvol_only=float(r2_iv),
                rho_spread=float(_spearman(abs_curl, spread)),
                rho_invvol=float(_spearman(abs_curl, invvol)))


def _spearman(a, b):
    ra, rb = _rank(a), _rank(b)
    ra, rb = ra - ra.mean(), rb - rb.mean()
    d = np.sqrt((ra @ ra) * (rb @ rb))
    return float(ra @ rb / d) if d > 0 else 0.0


def _rank(v):
    o = np.argsort(v, kind="mergesort")
    r = np.empty(len(v), float)
    r[o] = np.arange(len(v), dtype=float)
    return r


def did(delta_treated, delta_control):
    """Difference-in-differences on per-triangle (post - pre) mean |c_T|, with a
    Welch 95% interval. Refuses rather than reporting a difference of means when
    either group is too small to have a spread -- a group of two is not a group."""
    a, b = np.asarray(delta_treated), np.asarray(delta_control)
    if len(a) < 3 or len(b) < 3:
        return dict(verdict="REFUSED", n_treated=len(a), n_control=len(b))
    va, vb = a.var(ddof=1) / len(a), b.var(ddof=1) / len(b)
    se = float(np.sqrt(va + vb))
    d = float(a.mean() - b.mean())
    return dict(did=d, se=se, lo=d - 1.96 * se, hi=d + 1.96 * se,
                t=d / se if se > 0 else float("nan"),
                mean_treated=float(a.mean()), mean_control=float(b.mean()),
                n_treated=len(a), n_control=len(b), verdict="OK")


def window_means(curl, spread, invvol, sl, drop=None):
    """Per-triangle window means and the count of usable minutes. drop, if given,
    is a boolean panel of minutes to exclude (used to drop zero-trade bars)."""
    c = np.abs(curl[:, sl]) * 1e4                     # basis points
    ok = np.isfinite(c)
    if drop is not None:
        ok &= ~drop[:, sl]
    n = ok.sum(1)
    with np.errstate(invalid="ignore"):
        mc = np.where(n > 0, np.nansum(np.where(ok, c, 0.0), 1) / np.maximum(n, 1), np.nan)
        ms = np.nanmean(np.where(np.isfinite(spread[:, sl]), spread[:, sl], np.nan), 1)
        mv = np.nanmean(np.where(np.isfinite(invvol[:, sl]), invvol[:, sl], np.nan), 1)
    return mc, ms, mv, n


