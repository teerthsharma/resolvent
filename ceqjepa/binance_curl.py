# Self-check: offline, synthetic, with a planted negative.

def _synth(n_nodes=14, n_min=800, seed=0, regime="spread", treat=None, rise=0.0):
    """Synthetic edge series on a complete graph over n_nodes assets.

    'spread'    every leg trades every minute; the quoted price is the true
                numeraire price plus a bid-ask jitter whose size is the leg's
                spread. Volume varies but is drawn INDEPENDENTLY of spread.
                Curl here is a spread phenomenon: the gate must PASS.
    'stale'     THE PLANTED NEGATIVE. Every leg is on the true price exactly --
                no spread at all, spreads drawn independently -- but each leg's
                quote is a LAST TRADE from up to k minutes ago, k set by the
                leg's own activity. Curl here is manufactured entirely by
                asynchronous quoting: the gate must VOID it.
    """
    rng = np.random.default_rng(seed)
    r = np.cumsum(rng.normal(0, 3e-4, size=(n_nodes, n_min + 64)), axis=1)
    edges = [(i, j) for i in range(n_nodes) for j in range(i + 1, n_nodes)]
    cx, _, _ = build_complex([("N%02d" % i, "N%02d" % j) for i, j in edges])
    series = []
    for (i, j) in cx.edges:
        halfspread = 10 ** rng.uniform(-4.3, -3.0)
        ntr = 10 ** rng.uniform(0.0, 2.7)
        if regime == "spread":
            om = r[i, 64:] - r[j, 64:] + rng.normal(0, halfspread, n_min)
            lag = np.zeros(n_min, dtype=int)
        else:
            halfspread = 10 ** rng.uniform(-4.3, -3.0)          # independent of ntr
            lag = rng.poisson(60.0 / ntr, n_min).clip(0, 60)
            idx = np.arange(n_min) + 64 - lag
            om = r[i, idx] - r[j, idx]
        series.append([om,
                       np.full(n_min, halfspread) * (1.0 + 0.2 * rng.normal(size=n_min)),
                       np.full(n_min, 1.0 / (1.0 + ntr))])
    curl, spread, invvol, _ = triangle_panels(cx, series)
    if treat is not None and rise > 0:
        m = np.array([bool(set(t) & set(treat)) for t in cx.triangles])
        curl[m, n_min // 2:] += rng.normal(0, rise, (int(m.sum()), n_min - n_min // 2))
    return cx, curl, spread, invvol


def selfcheck():
    n_min = 800
    half = slice(0, n_min // 2), slice(n_min // 2, n_min)

    print("(a) THE COMPLEX. d1 @ d0 == 0 is asserted inside build_complex(); a")
    print("    complex that fails it makes every curl below an arithmetic error.")
    cx, curl, spread, invvol = _synth(regime="spread")
    print("    %s" % cx)

    print("(b) THE NULL IS EXACT. Prices from a single numeraire have ZERO curl on")
    print("    every triangle, which is what makes departure from it meaningful.")
    rng = np.random.default_rng(1)
    r = rng.normal(size=cx.n_nodes)
    om = np.array([[r[i] - r[j]] for (i, j) in cx.edges], dtype=float)
    pure = [[om[e], np.zeros(1), np.zeros(1)] for e in range(len(cx.edges))]
    c0, _, _, _ = triangle_panels(cx, pure)
    print("    max |c_T| on a pure potential = %.3e" % float(np.abs(c0).max()))
    assert float(np.abs(c0).max()) < 1e-12

    print("(c) THE GATE, SPREAD REGIME. Curl driven by bid-ask jitter, volume drawn")
    print("    independently of spread. The gate must PASS or it can never pass.")
    mc, ms, mv, _ = window_means(curl, spread, invvol, half[0])
    g_ok = gate(mc, ms, mv)
    print("    beta_spread=%+.3f (t=%+.1f)  beta_invvol=%+.3f (t=%+.1f)  ->  %s"
          % (g_ok["beta_spread"], g_ok["t_spread"], g_ok["beta_invvol"],
             g_ok["t_invvol"], g_ok["verdict"]))
    assert g_ok["verdict"] == "PASS", "the gate rejects data it must accept"

    print("(d) THE PLANTED NEGATIVE. Same complex, ZERO spread contribution: every")
    print("    leg sits exactly on the true price but quotes it from up to 60")
    print("    minutes ago, with staleness set by its own activity. The curl here")
    print("    is 100%% microstructure. The gate must VOID it.")
    _, curl_s, spread_s, invvol_s = _synth(regime="stale", seed=3)
    mcs, mss, mvs, _ = window_means(curl_s, spread_s, invvol_s, half[0])
    g_bad = gate(mcs, mss, mvs)
    print("    beta_spread=%+.3f (t=%+.1f)  beta_invvol=%+.3f (t=%+.1f)  ->  %s"
          % (g_bad["beta_spread"], g_bad["t_spread"], g_bad["beta_invvol"],
             g_bad["t_invvol"], g_bad["verdict"]))
    print("    R2 spread-only = %.3f, R2 invvol-only = %.3f"
          % (g_bad["r2_spread_only"], g_bad["r2_invvol_only"]))
    assert g_bad["verdict"] == "VOID", \
        "THE GATE IS DECORATIVE: it passed data whose curl is pure staleness"
    print("    FIRED: staleness-only curl is VOIDed, spread-driven curl PASSes.")

    print("(e) THE DiD RECOVERS A PLANTED RISE AND ONLY A PLANTED RISE.")
    treat = [0, 1, 2]
    for rise, want in ((0.0, False), (6e-4, True)):
        _, cu, sp, iv = _synth(regime="spread", seed=7, treat=treat, rise=rise)
        pre = window_means(cu, sp, iv, half[0])[0]
        post = window_means(cu, sp, iv, half[1])[0]
        d = post - pre
        m = np.array([bool(set(t) & set(treat)) for t in cx.triangles])
        res = did(d[m], d[~m])
        sig = res["lo"] > 0
        print("    rise=%.0e -> DiD %+.3f bp  95%% CI [%+.3f, %+.3f]  n=%d/%d  sig=%s"
              % (rise, res["did"], res["lo"], res["hi"], res["n_treated"],
                 res["n_control"], sig))
        assert sig == want, "the DiD %s a planted effect" % ("missed" if want else "invented")
    print("    FIRED both ways: null is null, planted rise is detected.")

    print("(f) REFUSAL. A group of two is not a group.")
    print("    did([1,2], control) -> %s" % did([1.0, 2.0], np.zeros(50))["verdict"])
    assert did([1.0, 2.0], np.zeros(50))["verdict"] == "REFUSED"
    print("ALL SELF-CHECKS PASSED")


