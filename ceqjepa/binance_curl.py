"""Found-data curl response to do(delete edge): Binance spot pair removals, 2026-08-14.

THE INTERVENTION. Binance removed seven spot trading pairs at 2026-08-14 03:00 UTC:
APT/BTC, AR/BTC, A/USDC, BTTC/TRY, CYBER/USDC, LPT/BTC, WAL/FDUSD. The announcement
states the base and quote assets remain tradable on other pairs. That is do(delete
edge) with the NODES LEFT STANDING and every other edge still quoted -- the shape
every synthetic bed in this repo has had to manufacture.

VERIFIED IN THE DATA, not taken on the announcement's word: each removed pair has a
full 1440-row 1m file on 2026-08-13, a 180-row file on 2026-08-14 (00:00-02:59 UTC),
and no file on 2026-08-15. The cut is where the announcement says it is.

THE OBJECT. On spot pairs, log price is an edge cochain: for a pair with base b and
quote q, w(b->q) = log(close) is "one b buys e^w q", antisymmetric by construction.
A triangle (i,j,k) carries c_T = w(i->j) + w(j->k) + w(k->i), which is exactly the
triangular-arbitrage residual. Zero curl == prices are generated by a single
numeraire potential. Orientation is dr1.Complex's: d1 row = +e(a,b) +e(b,c) -e(a,c)
on sorted (a,b,c), which is that sum. The complex is built with dr1.Complex and its
d1 @ d0 == 0 is asserted before anything is measured; market_curl.pairing_complex is
the same construction but enumerates triples in O(n^3) over nodes, which is fine for
6 teams and not for 500 assets, so the triangles are enumerated off the adjacency
here and handed to the same Complex.

THE HYPOTHESIS. Removing an edge removes an arbitrage PATH, so curl on triangles
that still stand but shared a node with a removed edge should RISE after 03:00 UTC
relative to triangles that did not. The LEVELS question is already answered in the
literature (curl sits at the spread floor); the RESPONSE question is what is open.

THE GATE, AND IT RUNS FIRST. Klines are NOT synchronous. A 1m bar's close is a
last-trade price, not a simultaneous snapshot across three books, so a thin leg's
stale price manufactures curl that is pure microstructure. THE TEST: regress
pre-intervention per-triangle mean |c_T| on (a) the summed half-spread proxy of the
three legs and (b) the summed inverse volume of the three legs. If |c_T| tracks
1/volume rather than spread, the measurement is reading staleness and is VOID.
gate() returns that verdict and main() stops on it.

--selfcheck runs offline on synthetic data and carries a PLANTED NEGATIVE: a
staleness-only regime whose curl is manufactured entirely by asynchronous quoting.
The gate must VOID it. If it does not, the gate is decorative and every number
downstream is unearned.

RUN:  python -m ceqjepa.binance_curl --selfcheck     (offline, no network)
      python -m ceqjepa.binance_curl                  (downloads to the scratchpad)
"""

