def list_symbols():
    """Every spot symbol in the public bucket. Listed, never guessed -- AUSDC is
    A/USDC and ARBTC is AR/BTC, and no naming convention tells you that."""
    path = os.path.join(_cache(), "symbols.json")
    if os.path.exists(path):
        return json.load(open(path))
    syms, marker = [], ""
    while True:
        url = LIST_URL + ("&marker=" + urllib.parse.quote(marker) if marker else "")
        body = urllib.request.urlopen(url, timeout=90).read().decode()
        page = [p.split("</Prefix>")[0].rstrip("/").rsplit("/", 1)[-1]
                for p in body.split("<Prefix>")[1:] if "</Prefix>" in p]
        page = [s for s in page if s and s != "klines"]
        syms.extend(page)
        if "<IsTruncated>true</IsTruncated>" not in body:
            break
        marker = body.split("<NextMarker>")[1].split("</NextMarker>")[0]
    syms = sorted(set(syms))
    json.dump(syms, open(path, "w"))
    return syms


def split_symbol(sym):
    for q in QUOTES:
        if sym.endswith(q) and len(sym) > len(q):
            return sym[:-len(q)], q
    return None


def fetch_day(sym, day):
    """(minute_index, close, high, low, n_trades) for one symbol-day, or None.
    A 404 is cached as a marker file: a pair that did not trade that day is a
    fact about the intervention, not a transient failure to retry."""
    raw = os.path.join(_cache(), "%s-%s.zip" % (sym, day))
    miss = raw + ".missing"
    if os.path.exists(miss):
        return None
    if not os.path.exists(raw):
        try:
            b = urllib.request.urlopen(BUCKET % (sym, sym, day), timeout=90).read()
        except urllib.error.HTTPError as e:
            if e.code == 404:
                open(miss, "w").close()
                return None
            raise
        open(raw, "wb").write(b)
    with zipfile.ZipFile(raw) as z:
        txt = z.read(z.namelist()[0]).decode()
    rows = list(csv.reader(io.StringIO(txt)))
    if not rows:
        return None
    if not rows[0][0].lstrip("-").replace(".", "", 1).isdigit():
        rows = rows[1:]                                    # newer files carry a header
    a = np.array(rows, dtype=np.float64)
    t = a[:, 0]
    t = t / 1e6 if t.max() > 1e15 else (t / 1e3 if t.max() > 1e12 else t)
    minute = np.rint((t - GRID_START.timestamp()) / 60.0).astype(np.int64)
    return minute, a[:, 4], a[:, 2], a[:, 3], a[:, 8]      # close, high, low, n_trades


def load_panel(symbols):
    """Dense minute grid per symbol: log close, half-spread proxy, inverse volume.
    NaN where the pair published no bar at all."""
    n_min = int((GRID_END - GRID_START).total_seconds() // 60)
    out = {}
    jobs = [(s, d) for s in symbols for d in DAYS]

    def one(j):
        try:
            return j[0], fetch_day(*j)
        except Exception as e:                 # a broken zip is a dropped symbol-day
            print("  warn %s %s: %s" % (ascii(j[0]), j[1], e), file=sys.stderr)
            return j[0], None

    with ThreadPoolExecutor(24) as ex:
        for sym, r in ex.map(one, jobs):
            if r is None:
                continue
            minute, close, high, low, ntr = r
            ok = (minute >= 0) & (minute < n_min) & (close > 0)
            if not ok.any():
                continue
            arr = out.setdefault(sym, np.full((3, n_min), np.nan))
            m = minute[ok]
            arr[0, m] = np.log(close[ok])
            arr[1, m] = (high[ok] - low[ok]) / (2.0 * close[ok])
            arr[2, m] = 1.0 / (1.0 + ntr[ok])
    return out, n_min


