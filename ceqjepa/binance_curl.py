# The complex and the cochain.

def build_complex(edges):
    """edges: iterable of (u, v) asset-name pairs that are quoted. Triangles are
    triples all three of whose pairs are quoted; a triple missing one quote is not
    a triangle and is dropped, not imputed."""
    nodes = sorted({x for e in edges for x in e})
    ix = {a: i for i, a in enumerate(nodes)}
    adj = {}
    have = set()
    for u, v in edges:
        i, j = ix[u], ix[v]
        adj.setdefault(i, set()).add(j)
        adj.setdefault(j, set()).add(i)
        have.add((min(i, j), max(i, j)))
    tri = []
    for a in sorted(adj):
        nb = sorted(x for x in adj[a] if x > a)
        for b, c in itertools.combinations(nb, 2):
            if (b, c) in have:
                tri.append((a, b, c))
    cx = Complex(len(nodes), tri)
    assert float(np.abs(cx.d1 @ cx.d0).max()) < 1e-12, \
        "d1 @ d0 != 0: this is not a complex and every curl below is arithmetic error"
    return cx, nodes, ix


def triangle_panels(cx, edge_series):
    """(curl, spread, invvol, any_stale) as (n_triangles, n_minutes).

    any_stale marks triangle-minutes where at least one leg published a bar with
    ZERO trades in it -- a bar whose close is literally the previous close carried
    forward. It is the sharpest staleness flag the kline schema affords, and the
    gate is run a second time with those minutes dropped so that a VOID verdict
    cannot be blamed on not having tried the obvious repair.

    edge_series[e] = (log_price_series_oriented_low_to_high, half_spread, invvol)
    for cx.edges[e]. The curl is taken by index rather than by d1 @ omega because
    d1 is mostly zeros and 0 * nan = nan -- a matmul would poison every triangle
    the moment one pair went unquoted for one minute.
    """
    eix = {e: i for i, e in enumerate(cx.edges)}
    OM = np.stack([edge_series[i][0] for i in range(len(cx.edges))])
    HS = np.stack([edge_series[i][1] for i in range(len(cx.edges))])
    IV = np.stack([edge_series[i][2] for i in range(len(cx.edges))])
    ia = np.array([eix[(t[0], t[1])] for t in cx.triangles])
    ib = np.array([eix[(t[1], t[2])] for t in cx.triangles])
    ic = np.array([eix[(t[0], t[2])] for t in cx.triangles])
    stale = (IV[ia] >= 1.0) | (IV[ib] >= 1.0) | (IV[ic] >= 1.0)
    return (OM[ia] + OM[ib] - OM[ic], HS[ia] + HS[ib] + HS[ic],
            IV[ia] + IV[ib] + IV[ic], stale)


