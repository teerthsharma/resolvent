# 4. Jacobian oracle is exact on both beds
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("kind,params", [("delay", dict(d=4)), ("powerlaw", dict(H=0.75))])
def test_jacobian_oracle_matches_independent_finite_difference(kind, params):
    """`bump` reads the analytic Jacobian column straight off the kernel;
    `finite_diff_jacobian_column` recomputes it via `bed_k.rebuild` (the
    generator's own forward pass) at a central difference, eps=1e-6,
    float64. `bump` never calls `rebuild` and `finite_diff_jacobian_column`
    never reads `bed["K"]` directly -- two independent routes to the same
    number, which is what makes the agreement a check rather than an
    identity (MISTAKES.md V-3).

    z = K @ b is exactly linear in b, so central-difference truncation error
    is zero in exact arithmetic; the only error source is float64 rounding,
    orders of magnitude under 1e-9.
    """
    n, seed = 300, 0
    bed = bed_k.build(kind, n, seed, **params)
    eps = 1e-6
    max_err = 0.0
    for p in (0, 1, n // 3, n // 2, n - 2, n - 1):
        analytic = bed_k.bump(bed, p, eps)
        fd = bed_k.finite_diff_jacobian_column(bed, p, eps)
        max_err = max(max_err, float(np.max(np.abs(analytic - fd))))
    assert max_err <= 1e-9, f"{kind}: analytic vs finite-diff Jacobian differ by {max_err}"


