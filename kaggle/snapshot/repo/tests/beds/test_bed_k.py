# 6. seeded reproducibility
# ---------------------------------------------------------------------------


def test_seeded_reproducibility_both_beds():
    d1 = bed_k.build_delay(500, 4, seed=7)
    d2 = bed_k.build_delay(500, 4, seed=7)
    assert np.array_equal(d1["b"], d2["b"])
    assert np.array_equal(d1["z"], d2["z"])
    d3 = bed_k.build_delay(500, 4, seed=8)
    assert not np.array_equal(d1["b"], d3["b"])
    assert not np.array_equal(d1["z"], d3["z"])

    p1 = bed_k.build_powerlaw(500, 0.75, seed=7)
    p2 = bed_k.build_powerlaw(500, 0.75, seed=7)
    assert np.array_equal(p1["b"], p2["b"])
    assert np.array_equal(p1["z"], p2["z"])
    p3 = bed_k.build_powerlaw(500, 0.75, seed=8)
    assert not np.array_equal(p1["b"], p3["b"])
    assert not np.array_equal(p1["z"], p3["z"])
