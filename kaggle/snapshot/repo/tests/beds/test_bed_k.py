@pytest.mark.parametrize("H", [0.3, 0.5, 1.0, 1.2])
def test_powerlaw_bed_refuses_outside_the_stationarity_box(H):
    """CEQ_V15_CONTRACT.md's power-law clause states H > 0.5 with no upper
    bound; ARFIMA(0, d, 0) with d = H - 1/2 is finite-variance/stationary
    only for |d| < 0.5, i.e. H strictly in (0.5, 1.0). H=0.5 (white noise,
    excluded by the contract's own '>') and H=1.0 (alpha=0.5, the boundary
    where GL weight energy stops being square-summable) must both raise --
    the box is closed on both ends, not just the one the contract wrote out.
    A generator that silently built a corpus at H=1.0 would hand H-recovery
    a label with no population Hurst exponent to recover.
    """
    with pytest.raises(ValueError):
        bed_k.build_powerlaw(64, H, seed=0)


def test_powerlaw_bed_builds_inside_the_stationarity_box():
    """V-8's rule, applied to a refusal: a gate that rejects everything is as
    vacuous as one that accepts everything. Confirms the box has a non-empty
    interior on the SAME code path as the refusal test above."""
    bed = bed_k.build_powerlaw(64, 0.75, seed=0)
    assert bed["z"].shape == (64,)
    assert np.all(np.isfinite(bed["z"]))


