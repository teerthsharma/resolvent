"""BED-K and the interventional channel -- CEQ_V15_CONTRACT.md PART III.

BED-K's whole reason to exist is that every corpus in the campaign up to this
file is Markov-generated (WHERE WE ARE: "no label has ever contained a
delayed cause"). That is a claim about the LABEL's dependency structure, and
a claim about dependency structure is not established by eyeballing a
formula -- it has to be measured against an instrument that could, in
principle, find the opposite answer. Every test below is built so a broken
`ceq/beds/bed_k.py` fails it:

  1. scan-blindness is measured, not asserted, and paired with an AR(1)
     control so a fit routine that is simply broken (always reads R^2~0)
     cannot hide behind "well, scan-blind was expected anyway" -- MISTAKES.md
     V-8, "the PASS half's label is constant."
  2. attention-reachability is a real reconstruction, not a claim.
  3. the Hurst estimator ships with the white-noise must-fire the contract
     names by clause, plus the AR(0.5) reading the contract warns is where
     R/S (not this estimator) reads 0.75 and is wrong.
  4. the Jacobian oracle is checked against an INDEPENDENT recomputation
     (`bed_k.rebuild`, which never calls `bed_k.bump`), not against itself.
  5. every bump is checked to move the label where the kernel says it
     should, AND to leave it bitwise untouched where the kernel is zero --
     MISTAKES.md V-9, "a repair that changes nothing," has a live twin here:
     a do()-bit that moves nothing would be exactly that pattern.
  6. reproducibility is checked both ways: same seed matches, different seed
     differs. A generator that ignores its seed entirely would pass a
     same-seed-only check.

Run order: this file is authored, and shown red, BEFORE `ceq/beds/bed_k.py`
exists (V15_N4_BEDK.md carries that transcript). Every numeric threshold
below is justified in its own docstring or comment, not chosen after seeing
what passes -- most are backed by a scratch measurement cited inline.
"""
from __future__ import annotations

import numpy as np
import pytest

from ceq.beds import bed_k


def _ar1(n: int, phi: float, seed: int) -> np.ndarray:
    """A genuine AR(1): w_i = phi*w_{i-1} + eps_i. Used only as a control
    series (never as a bed), so it lives here rather than in bed_k.py."""
    rng = np.random.default_rng(seed)
    eps = rng.standard_normal(n)
    w = np.zeros(n)
    for t in range(1, n):
        w[t] = phi * w[t - 1] + eps[t]
    return w


# ---------------------------------------------------------------------------
# 1. delay bed is scan-blind, AR(1) control confirms the fit routine works
# ---------------------------------------------------------------------------


def test_delay_bed_scan_blind_but_ar1_control_reaches_0_99():
    """Fits y_i = alpha*y_{i-1} + beta*x_i by least squares, giving the
    recurrence the MOST generous possible state: the delay bed's own true
    previous label (a real scan only has its own prior output, never ground
    truth), so a low R^2 here cannot be blamed on a weak state proxy.

    Why 0.05. `b` is iid, so z_{i-1} = b_{i-1-d} and z_i = b_{i-d} are drawn
    from different, independent positions of the SAME noise for any d >= 1 --
    population R^2 is exactly 0, not approximately 0. The finite-sample noise
    floor with p=2 regressors at n=2048 is ~p/(n-1) ~ 0.001; measured
    directly over 30 seeds at d=4 it was [-0.0027, 0.0028]. 0.05 is ~18x that
    measured ceiling and a two-order-of-magnitude margin below the AR(1)
    control's 0.99, so the two halves cannot be confused by threshold choice.
    """
    n, d, seed = 2048, 5, 0
    bed = bed_k.build_delay(n, d, seed)
    z, b = bed["z"][d:], bed["b"][d:]
    _, _, r2_delay = bed_k.fit_first_order_recurrence(z, b)

    THRESH = 0.05
    assert r2_delay < THRESH, (
        f"first-order recurrence explains the delay label (R2={r2_delay}); "
        "the delay bed is not scan-blind at d={d}"
    )

    # V-8's rule: check the PASS half's label is non-degenerate before the
    # FAIL half is interesting. Here that means showing the FIT ITSELF can
    # reach a high R2 on data actually generated by this recurrence form --
    # otherwise a low R2 above just means "the lstsq call is broken."
    a_true = 0.8
    rng = np.random.default_rng(seed + 1)
    eps = rng.standard_normal(n)
    w = np.zeros(n)
    for t in range(1, n):
        w[t] = a_true * w[t - 1] + eps[t]
    alpha_hat, beta_hat, r2_ar1 = bed_k.fit_first_order_recurrence(w, eps)
    assert r2_ar1 >= 0.99, (
        f"fit routine reaches only R2={r2_ar1} on a true AR(1) series "
        f"(alpha_hat={alpha_hat}, beta_hat={beta_hat}); it is too weak for "
        "the scan-blind reading above to mean anything"
    )


# ---------------------------------------------------------------------------
# 2. delay bed is attention-reachable
# ---------------------------------------------------------------------------


def test_delay_bed_is_attention_reachable_to_1e_12():
    """A single hand-set attention head -- one-hot positional query/key coding
    offset by d, fixed temperature -- reproduces the delay label for i >= d
    (i < d has no valid source position; the label itself is undefined
    there, so callers do not compare it).

    Precision bound: softmax residual off the true position is bounded by
    (n-1)*exp(-temperature). At temperature=45, n=500: 499*exp(-45) ~ 1.3e-17,
    far under the 1e-12 the must-fire asks for. Measured directly: max abs
    error 8.67e-19 at n=500, d=4 (scratch run backing this test).
    """
    n, d, seed = 500, 7, 3
    bed = bed_k.build_delay(n, d, seed)
    # Read ONLY the two fields build()'s manifest actually exposes (`b` and
    # `pos`) -- not `bed["K"]`. A delay is a POSITIONAL operation, so passing
    # `pos` explicitly (rather than letting the head assume index order) is
    # what makes this a claim about a channel a real arm could also read,
    # per the coordinator's cross-node finding: an arm given content only,
    # no positional feature, would fail this bed for a reason that has
    # nothing to do with memory kernels, and the two failure causes must not
    # be allowed to collapse into one number.
    pred = bed_k.hard_delay_attention(bed["b"], d, pos=bed["pos"])
    err = float(np.max(np.abs(pred[d:] - bed["z"][d:])))
    assert err <= 1e-12, f"attention head does not reproduce the delay label: max err={err}"


