# 5. the bumps actually move the label -- both halves
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("kind,params", [("delay", dict(d=4)), ("powerlaw", dict(H=0.75))])
def test_bump_moves_z_exactly_where_kernel_nonzero_and_nowhere_else(kind, params):
    """MISTAKES.md V-9: "a repair that changes nothing." A do()-bit that
    moves the label by exactly 0.0 everywhere is that pattern wearing an
    interventional-channel costume, and `tests/loop/test_every_boundary_
    node_can_propagate.py` already has a live instance of it -- this is the
    same check, run against BED-K's own bump.

    Both halves are required (V-8's non-degeneracy rule, restated for a
    boolean mask rather than a class label): the nonzero set must be neither
    empty nor everything, checked directly, or the two assertions below have
    no content.
    """
    n, seed = 200, 0
    bed = bed_k.build(kind, n, seed, **params)
    p = n // 2
    eps = 1e-3
    b2 = bed["b"].copy()
    b2[p] += eps
    z2 = bed_k.rebuild(bed, b2)
    diff = z2 - bed["z"]

    nonzero_mask = bed["K"][:, p] != 0.0
    assert 0 < int(nonzero_mask.sum()) < n, (
        f"{kind}: kernel column p={p} is degenerate (all-zero or all-nonzero); "
        "this test would have no discriminating power"
    )
    assert np.all(diff[nonzero_mask] != 0.0), f"{kind}: bump did not move z where K != 0"
    assert np.all(diff[~nonzero_mask] == 0.0), f"{kind}: bump moved z where K == 0 (not exact)"


