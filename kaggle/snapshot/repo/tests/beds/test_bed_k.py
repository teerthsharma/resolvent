def test_hurst_estimator_white_noise_must_fire():
    """CEQ_V15_CONTRACT.md PART III: "the Hurst covariate ships ONLY with its
    white-noise must-fire." White noise has true H=0.5 and no long-range
    structure at all; this is the estimator's null case.

    Averaged over 5 seeds (n=8192 each) to keep the check from being a
    single noisy draw -- MISTAKES.md M-4 warns against reading single-seed
    variability as if it were the truth. Tolerance 0.15 measured directly:
    5-seed means across two independent seed blocks (0-4 and repeats) landed
    at 0.477-0.513, i.e. within 0.05 of 0.5 both times.
    """
    n = 8192
    ests = [bed_k.estimate_hurst_dfa(np.random.default_rng(seed).standard_normal(n))
            for seed in range(5)]
    h_hat = float(np.mean(ests))
    assert abs(h_hat - 0.5) < 0.15, f"DFA reads H={h_hat} on white noise (true H=0.5): {ests}"


def test_hurst_estimator_ar05_is_not_the_rs_bias():
    """CEQ_V15_CONTRACT.md PART III, verbatim: "the author's R/S read 0.75 on
    AR(0.5): biased." AR(0.5) is short-memory only (true H=0.5); R/S reads it
    high. This is the must-fire that an estimator claiming to be calibrated
    has to pass: report the SAME estimator's reading on this EXACT case and
    require it nowhere near the biased value.

    0.65 sits at the midpoint between the unbiased truth (0.5) and R/S's
    documented failure (0.75) -- closer to either would make the threshold
    do the work instead of the estimator.
    """
    n = 8192
    ests = [bed_k.estimate_hurst_dfa(_ar1(n, 0.5, seed)) for seed in range(5)]
    h_hat = float(np.mean(ests))
    assert h_hat < 0.65, (
        f"DFA reads H={h_hat} on AR(0.5) -- inside R/S's documented biased "
        f"range (0.75); this estimator is not the calibrated one the "
        f"contract asks for: {ests}"
    )


def test_hurst_estimator_recovers_known_H_on_the_powerlaw_bed():
    """Generate at a known H, estimate it back. n=8192, H=0.75, 5 seeds
    (100-104, a different block from the white-noise/AR(0.5) seeds above so
    this is not the same draws re-used). Tolerance 0.15 measured directly:
    mean H_hat=0.812 on this exact seed block (bias +0.062); a second,
    independent seed block (0-4) gave mean 0.787 (bias +0.037). Both well
    inside 0.15 with room to spare; a broken kernel (wrong sign on the
    exponent, off-by-one in the causal mask, or H substituted for 1-H) reads
    far outside it -- e.g. H_hat~0.5 for an accidentally-white kernel.
    """
    n, H_true, seed0 = 8192, 0.75, 100
    ests = []
    for i in range(5):
        bed = bed_k.build_powerlaw(n, H_true, seed=seed0 + i)
        ests.append(bed_k.estimate_hurst_dfa(bed["z"]))
    h_hat = float(np.mean(ests))
    assert abs(h_hat - H_true) < 0.15, f"H_hat={h_hat} vs H_true={H_true}: {ests}"


